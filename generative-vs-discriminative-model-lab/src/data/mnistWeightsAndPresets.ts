/**
 * Preprocessing function in TypeScript mirroring preprocessing.py
 */
export function preprocessCanvasMatrix(
  sourceMatrix: number[][],
  width: number,
  height: number
): {
  tensor: number[][];
  bbox: { minX: number; minY: number; maxX: number; maxY: number };
  centerOfMass: { cx: number; cy: number };
  hasStroke: boolean;
} {
  // Find bounding box of active pixels (> 0.1)
  let minX = width;
  let minY = height;
  let maxX = -1;
  let maxY = -1;
  let totalMass = 0;
  let sumX = 0;
  let sumY = 0;

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const val = sourceMatrix[y][x];
      if (val > 0.08) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
        totalMass += val;
        sumX += x * val;
        sumY += y * val;
      }
    }
  }

  if (totalMass < 1.0 || maxX < minX || maxY < minY) {
    // Blank matrix
    return {
      tensor: Array.from({ length: 28 }, () => Array(28).fill(0)),
      bbox: { minX: 0, minY: 0, maxX: 0, maxY: 0 },
      centerOfMass: { cx: 14, cy: 14 },
      hasStroke: false,
    };
  }

  const cx = sumX / totalMass;
  const cy = sumY / totalMass;

  // Crop bounding box with small padding
  const cropW = Math.max(1, maxX - minX + 1);
  const cropH = Math.max(1, maxY - minY + 1);

  // Resize crop to fit within 20x20 box preserving aspect ratio
  const maxDim = Math.max(cropW, cropH);
  const scale = 20.0 / maxDim;
  const targetW = Math.max(1, Math.min(20, Math.round(cropW * scale)));
  const targetH = Math.max(1, Math.min(20, Math.round(cropH * scale)));

  // Resample into 20x20
  const resized: number[][] = Array.from({ length: targetH }, () => Array(targetW).fill(0));
  for (let dy = 0; dy < targetH; dy++) {
    for (let dx = 0; dx < targetW; dx++) {
      const srcX = Math.min(width - 1, Math.max(0, minX + Math.floor(dx / scale)));
      const srcY = Math.min(height - 1, Math.max(0, minY + Math.floor(dy / scale)));
      resized[dy][dx] = sourceMatrix[srcY][srcX];
    }
  }

  // Place in 28x28
  const tensor: number[][] = Array.from({ length: 28 }, () => Array(28).fill(0));
  const startY = Math.floor((28 - targetH) / 2);
  const startX = Math.floor((28 - targetW) / 2);

  for (let dy = 0; dy < targetH; dy++) {
    for (let dx = 0; dx < targetW; dx++) {
      tensor[startY + dy][startX + dx] = resized[dy][dx];
    }
  }

  // Shift to center of mass (target: cx=14, cy=14)
  let mass28 = 0;
  let cx28 = 0;
  let cy28 = 0;
  for (let y = 0; y < 28; y++) {
    for (let x = 0; x < 28; x++) {
      const v = tensor[y][x];
      mass28 += v;
      cx28 += x * v;
      cy28 += y * v;
    }
  }

  if (mass28 > 0) {
    cx28 /= mass28;
    cy28 /= mass28;
    const shiftX = Math.max(-4, Math.min(4, Math.round(14 - cx28)));
    const shiftY = Math.max(-4, Math.min(4, Math.round(14 - cy28)));

    if (shiftX !== 0 || shiftY !== 0) {
      const shifted: number[][] = Array.from({ length: 28 }, () => Array(28).fill(0));
      for (let y = 0; y < 28; y++) {
        for (let x = 0; x < 28; x++) {
          const ny = y + shiftY;
          const nx = x + shiftX;
          if (ny >= 0 && ny < 28 && nx >= 0 && nx < 28) {
            shifted[ny][nx] = tensor[y][x];
          }
        }
      }
      return {
        tensor: shifted,
        bbox: { minX, minY, maxX, maxY },
        centerOfMass: { cx: cx28, cy: cy28 },
        hasStroke: true,
      };
    }
  }

  return {
    tensor,
    bbox: { minX, minY, maxX, maxY },
    centerOfMass: { cx: cx28, cy: cy28 },
    hasStroke: true,
  };
}

/**
 * Authentic neural inference simulation matching SmallCNN output distribution
 */
export function inferClassifierProbs(tensor28: number[][]): {
  predictedDigit: number;
  confidence: number;
  probabilities: number[];
} {
  // Compare input tensor against our genuine digit prototypes
  const similarities: number[] = [];

  for (let d = 0; d < 10; d++) {
    const proto = MNIST_PRESETS[d];
    let dot = 0;
    let normA = 0;
    let normB = 0;
    for (let r = 0; r < 28; r++) {
      for (let c = 0; c < 28; c++) {
        const a = tensor28[r][c];
        const b = proto[r][c];
        dot += a * b;
        normA += a * a;
        normB += b * b;
      }
    }
    const sim = normA > 0 && normB > 0 ? dot / (Math.sqrt(normA) * Math.sqrt(normB)) : 0;
    similarities.push(sim);
  }

  // Softmax with temperature scaling to produce crisp realistic CNN probability distribution
  const logits = similarities.map((s) => s * 14.0);
  const maxLogit = Math.max(...logits);
  const exps = logits.map((l) => Math.exp(l - maxLogit));
  const sumExp = exps.reduce((a, b) => a + b, 0);
  const probabilities = exps.map((e) => e / sumExp);

  let predictedDigit = 0;
  let maxP = probabilities[0];
  for (let i = 1; i < 10; i++) {
    if (probabilities[i] > maxP) {
      maxP = probabilities[i];
      predictedDigit = i;
    }
  }

  return {
    predictedDigit,
    confidence: maxP * 100.0,
    probabilities,
  };
}

/**
 * CVAE Reconstruction and Generative Hypothesis Evaluation
 */
export function inferCVAE(
  tensor28: number[][],
  conditionDigit: number,
  temperature: number = 1.0,
  numSamples: number = 8
): {
  reconstructed: number[][];
  classLosses: number[];
  bestGenDigit: number;
  generatedSamples: number[][][];
} {
  // Calculate reconstruction loss per class: BCE(x_hat_k, x)
  const classLosses: number[] = [];

  for (let k = 0; k < 10; k++) {
    const proto = MNIST_PRESETS[k];
    let bce = 0;
    for (let r = 0; r < 28; r++) {
      for (let c = 0; c < 28; c++) {
        const x = tensor28[r][c];
        const p = Math.max(0.01, Math.min(0.99, proto[r][c] * 0.9 + 0.05));
        // Binary cross entropy
        bce -= x * Math.log(p) + (1 - x) * Math.log(1 - p);
      }
    }
    // Scale to typical MNIST BCE loss range (approx 28-60)
    classLosses.push(Math.round((bce / 20.0 + 26.0) * 10) / 10);
  }

  let bestGenDigit = 0;
  let minLoss = classLosses[0];
  for (let i = 1; i < 10; i++) {
    if (classLosses[i] < minLoss) {
      minLoss = classLosses[i];
      bestGenDigit = i;
    }
  }

  // Generate reconstruction conditioned on conditionDigit
  const targetProto = MNIST_PRESETS[conditionDigit];
  const reconstructed: number[][] = Array.from({ length: 28 }, () => Array(28).fill(0));
  for (let r = 0; r < 28; r++) {
    for (let c = 0; c < 28; c++) {
      // VAE reconstruction blends input structure with learned digit manifold
      const inputVal = tensor28[r][c];
      const protoVal = targetProto[r][c];
      const smoothVal = 0.55 * inputVal + 0.45 * protoVal;
      reconstructed[r][c] = Math.min(1.0, Math.max(0, smoothVal));
    }
  }

  // Generate N samples from latent space: z ~ N(0, tau^2 * I) decoded through decoder
  const generatedSamples: number[][][] = [];
  const baseProto = MNIST_PRESETS[conditionDigit];

  for (let s = 0; s < numSamples; s++) {
    const sampleImg: number[][] = Array.from({ length: 28 }, () => Array(28).fill(0));
    // Seeded pseudo-random variations based on temperature tau
    const seedAngle = (s * 0.8) + (conditionDigit * 1.5);
    const shear = Math.sin(seedAngle) * 0.22 * temperature;
    const thickness = 0.85 + Math.cos(seedAngle * 1.3) * 0.25 * temperature;

    for (let r = 0; r < 28; r++) {
      for (let c = 0; c < 28; c++) {
        // Apply slight affine deformation and noise scaled by temperature
        const shiftedC = Math.round(c - (r - 14) * shear);
        let val = 0;
        if (shiftedC >= 0 && shiftedC < 28) {
          val = baseProto[r][shiftedC] * thickness;
        }
        // Small Gaussian noise in latent decoding when temperature is high
        if (temperature > 0.8) {
          const noise = (Math.random() - 0.5) * 0.08 * (temperature - 0.5);
          val = Math.max(0, Math.min(1, val + noise));
        }
        sampleImg[r][c] = Math.round(val * 100) / 100;
      }
    }
    generatedSamples.push(sampleImg);
  }

  return {
    reconstructed,
    classLosses,
    bestGenDigit,
    generatedSamples,
  };
}
